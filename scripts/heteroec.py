#!/usr/bin/env python3
"""Helpers for the heterogeneous error-correction experiments (Table 1 and Table 3).

Subcommands:
  table1-sweep  Run the naive logical T gate (Fig. 5, no trailing Hadamards)
                for every (d_data, d_anc) pair with the mean decoding times,
                and write a CSV. Table 1 had no generator in the repository.
  optimal       From a sweep CSV, pick the lowest error under each space budget
                and print a Markdown table plus LaTeX rows in the paper's format.

Table 3's sweep (d_q, d_anc[0], d_anc[1]) is generated by
examples/logicalT-exp/hybrid/collect_mean_autocorrected.py.
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
import itertools
import re
import subprocess
import sys
import tempfile
from pathlib import Path

PACKAGE_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = PACKAGE_DIR.parent
ARTIFACTS_DIR = None
MEAN_DIR = PACKAGE_DIR / "examples" / "logicalT-exp" / "mean"

# The logical T gate of Fig. 5 (examples/logicalT.ft), with the ancilla's scheme
# as a parameter. Updated 2026-11-13: S-correction teleported with a prepared
# ancilla (prepare plus faultyS injection), X measurement in the
# intermediate statement and the ZZ-guarded Z correction.
GATE_T = """def gateT(q: Codeblock) {{
  logical anc := new surface_code_{d_anc};
  prepare(anc);
  // call prepare_magic_state(anc);
  if M(ZZ)[q[0], anc]; {{
    // intermediate statement
    if M(X)[anc]; then Z[q[0]];
  }} then {{
    prepare(anc);
    faultyS[anc];
    // LC S-resource injection; keep the T-resource preparation placeholder above.
    if M(ZZ)[q[0], anc]; {{
      // intermediate statement
      if M(X)[anc]; then Z[q[0]];
    }} then Z[q[0]];
  }};
  release(anc);
}}

program {{
  logical q := new surface_code_{d_data};
  call gateT(q);
  release(q);
}}
"""


def main() -> int:
    global MEAN_DIR, ARTIFACTS_DIR
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    sweep = sub.add_parser("table1-sweep", help="run the (d_data, d_anc) sweep for Table 1")
    sweep.add_argument("--distances", default="27,29,31", help="comma-separated code distances")
    sweep.add_argument("--semantics", choices=("v1", "v2"), default="v2")
    sweep.add_argument("--output", type=Path, required=True, help="CSV output path")

    sweep.add_argument("--mean-dir", type=Path, default=MEAN_DIR)
    sweep.add_argument("--artifacts-dir", type=Path)

    optimal = sub.add_parser("optimal", help="best error under each space budget")
    optimal.add_argument("--csv", type=Path, required=True)
    optimal.add_argument("--budgets", required=True, help="comma-separated qubit budgets (strict <)")
    optimal.add_argument("--style", choices=("table1", "table3"), required=True)
    optimal.add_argument("--output", type=Path, help="also write the tables to this file")

    optimal.add_argument("--format", choices=("markdown", "latex"), default="markdown")
    args = parser.parse_args()
    if args.command == "table1-sweep":
        MEAN_DIR = args.mean_dir.resolve()
        ARTIFACTS_DIR = args.artifacts_dir
        return table1_sweep(args)
    return optimal_table(args)


# ---------------------------------------------------------------------------
# Table 1 sweep
# ---------------------------------------------------------------------------


def table1_sweep(args: argparse.Namespace) -> int:
    distances = [int(d) for d in args.distances.split(",") if d.strip()]
    hardware = read_hardware(MEAN_DIR / f"d={max(distances)}_naive.ft")
    schemes = {d: read_scheme(d) for d in distances}
    rows = []
    with tempfile.TemporaryDirectory(prefix="ftqp-table1-") as tmp:
        for d_data, d_anc in itertools.product(distances, repeat=2):
            text = "\n\n".join(
                [hardware, *(schemes[d] for d in sorted({d_data, d_anc})), GATE_T.format(d_data=d_data, d_anc=d_anc)]
            )
            path = Path(tmp) / f"logicalT_d{d_data}_{d_anc}.ft"
            path.write_text(text, encoding="utf-8")
            err, time_cycles, space = run_ftqp(path, args.semantics)
            rows.append((d_data, d_anc, err, time_cycles, space))
            print(f"  d_data={d_data} d_anc={d_anc}: error={err:.4f}% time={time_cycles:.0f} cycles space={space}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["d_data", "d_anc", "error_percent", "time_se_cycles", "space_physical_qubits"])
        for d_data, d_anc, err, time_cycles, space in rows:
            writer.writerow([d_data, d_anc, f"{err:.6f}", f"{time_cycles:.6f}", space])
    print(f"wrote {args.output}")
    return 0


def read_hardware(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"hardware\s+superconducting\s*=\s*\{.*?\};", text, re.DOTALL)
    if not match:
        raise SystemExit(f"{path}: could not find hardware block")
    return match.group(0)


def read_scheme(distance: int) -> str:
    """surface_code_<d> with the mean decoding time, from the mean/ examples."""
    path = MEAN_DIR / f"d={distance}_naive.ft"
    if not path.exists():
        raise SystemExit(f"no mean-decoding scheme for d={distance} ({path} missing)")
    text = path.read_text(encoding="utf-8")
    match = re.search(
        rf"qecc\s+surface_code_{distance}\s+using\s+superconducting\s*=\s*\{{.*?\n\}};",
        text,
        re.DOTALL,
    )
    if not match:
        raise SystemExit(f"{path}: could not find surface_code_{distance}")
    scheme = match.group(0)
    if "faultyS:" not in scheme:
        # Historical input directories may predate the explicit S-resource model.
        scheme = scheme.replace('  OPF: {\n', '  OPF: {\n    faultyS: { arity: 1, time: "0", pF: "0.0046", "#ancilla": "0" },\n', 1)
    return scheme


def run_ftqp(path: Path, semantics: str) -> tuple[float, float, int]:
    completed = subprocess.run(
        [sys.executable, "-m", "ftqp_prototype", str(path), "--trace", "--no-circuit", "--semantics", semantics],
        cwd=REPO_ROOT,
        text=True,
        capture_output=True,
        check=False,
        timeout=30,
    )
    if ARTIFACTS_DIR is not None:
        case = ARTIFACTS_DIR / path.stem
        case.mkdir(parents=True, exist_ok=False)
        shutil.copy2(path, case / "input.ft")
        (case / "run.log").write_text(completed.stdout + "\nSTDERR:\n" + completed.stderr)
        (case / "run.json").write_text(json.dumps({"exit_code": completed.returncode, "semantics": semantics, "command": completed.args}))
    if completed.returncode != 0:
        raise SystemExit(f"{path.name} failed:\n{completed.stderr or completed.stdout}")
    out = completed.stdout
    release_q = out.rfind("release q")
    eps = re.findall(r"\bq\[0\]=([0-9.eE+-]+)(?:@[A-Za-z_][A-Za-z0-9_]*)?", out[:release_q])
    time_match = re.search(r"^time \(#SE cycles\)\s+([0-9.eE+-]+)\s*$", out, re.MULTILINE)
    space_match = re.search(r"^space\s+([0-9]+)\s+physical qubits\s*$", out, re.MULTILINE)
    if not (eps and time_match and space_match):
        raise SystemExit(f"{path.name}: could not parse estimator output")
    return float(eps[-1]) * 100.0, float(time_match.group(1)), int(space_match.group(1))


# ---------------------------------------------------------------------------
# Optimal configuration per space budget
# ---------------------------------------------------------------------------


def optimal_table(args: argparse.Namespace) -> int:
    budgets = [int(b) for b in args.budgets.split(",") if b.strip()]
    with args.csv.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    config_cols = [c for c in rows[0] if c.startswith("d")] if rows else []

    md = ["| Space budget | Optimal error rate | Distances | Time cost | Space cost |", "|---|---|---|---|---|"]
    tex = []
    for budget in budgets:
        feasible = [r for r in rows if int(r["space_physical_qubits"]) < budget]
        if not feasible:
            md.append(f"| <{budget} | (none) | | | |")
            continue
        best = min(feasible, key=lambda r: (float(r["error_percent"]), float(r["time_se_cycles"])))
        err = float(best["error_percent"])
        time_cycles = round(float(best["time_se_cycles"]))
        space = int(best["space_physical_qubits"])
        dists = ", ".join(f"{c}={best[c]}" for c in config_cols)
        md.append(f"| <{budget} | {err:.4f}% | {dists} | {time_cycles} cycles | {space} qubits |")
        if args.style == "table1":
            tex.append(
                rf"\(<{budget}\) qubits & {err:.2f}\% & "
                rf"\((d_{{\mathrm{{data}}}}={best['d_data']},d_{{\mathrm{{anc}}}}={best['d_anc']})\) & "
                rf"{time_cycles} cycles & {space} qubits\\"
            )
        else:
            tex.append(
                rf"$<{budget}$ qubits & ${err:.4f}\%$ & "
                rf"$(d_q = {best['d1_q']},\ d_{{\mathrm{{anc}}[0]}} = {best['d2_anc0']},\ "
                rf"d_{{\mathrm{{anc}}[1]}} = {best['d3_anc1']})$ & ${time_cycles}$ cycles \\"
            )
    text = "\n".join(md) + "\n\n% LaTeX rows\n" + "\n".join(tex) + "\n"
    if args.format == "latex":
        text = "\n".join(tex) + "\n"
    print(text, end="")
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
