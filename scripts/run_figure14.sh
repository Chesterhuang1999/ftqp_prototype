#!/usr/bin/env bash
# Logical T gate followed by 36 logical Hadamard gates: Fig. resource-result
# (Fig. 13 in the current arXiv-2608.04573 PDF, Fig. 14 in the first version).
#
# Row 1 (always): d-sweep under the mean decoding latency
#   (examples/logicalT-exp/mean/):
#   - implementations: naive (S-correction, variant A) and auto-corrected
#     (extra ancilla, Pauli correction only, variant B);
#   - odd d = 23..31: uniform, all codeblocks at distance d   (d=XX_*.ft);
#   - even d = 24..30: hybrid, data at d+1 and ancillas at d-1 (hybridXXYY_*.ft).
# Row 2, chosen by --row2:
#   latency     (default) decoding-latency sweep at d = 27, t_dec = 0..1000
#               (examples/logicalT-exp/latency/, regenerated by latency/generate.py;
#               set TDEC_LIST=0,50,... to change the latencies)
#   percentile  the old d-sweep under the 99.9th-percentile latency
#               (examples/logicalT-exp/99.9/); reproduces the old figure exactly
#
# Output per error semantics, in DIR/<semantics>/:
#   exp_tables.tex   pgfplots tables (row 1 + row 2)
#   exp_figure.tex   drop-in replacement for the paper's contents/exp.tex
#   figure13.pdf/png standalone render (needs pdflatex; scripts/plot_figure13.sh)
#
# Usage: scripts/run_figure14.sh [--semantics v1|v2|both] [--row2 latency|percentile] [--out DIR] [--data-root DIR]
#   v1 reproduces the numbers of the first paper version; v2 is the
#   source-aware error analysis of the revised Sec. 5 (default).
set -euo pipefail

SEMANTICS="v2"
ROW2="latency"
OUT=""
DATA_ROOT=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --semantics) SEMANTICS="$2"; shift 2 ;;
    --row2) ROW2="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --data-root) DATA_ROOT="$2"; shift 2 ;;
    -h|--help) sed -n '2,26p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PKG_DIR="$(dirname "$SCRIPT_DIR")"
PYTHON="${PYTHON:-python3}"
OUT="${OUT:-$PKG_DIR/results/figure14}"
EXP_DIR="$PKG_DIR/examples/logicalT-exp"
DATA_ROOT="${DATA_ROOT:-$EXP_DIR}"
if [[ "$ROW2" == latency && "$DATA_ROOT" != "$EXP_DIR" ]]; then
  echo "--data-root currently requires --row2 percentile" >&2; exit 2
fi

case "$SEMANTICS" in
  v1|v2) SEMANTICS_LIST=("$SEMANTICS") ;;
  both) SEMANTICS_LIST=(v1 v2) ;;
  *) echo "--semantics must be v1, v2 or both" >&2; exit 2 ;;
esac
case "$ROW2" in
  latency|percentile) ;;
  *) echo "--row2 must be latency or percentile" >&2; exit 2 ;;
esac

if [[ "$ROW2" == latency ]]; then
  "$PYTHON" "$EXP_DIR/latency/generate.py" ${TDEC_LIST:+--tdec "$TDEC_LIST"}
fi

for sem in "${SEMANTICS_LIST[@]}"; do
  target="$OUT/$sem/exp_tables.tex"
  mkdir -p "$OUT/$sem"
  if [[ "$ROW2" == percentile ]]; then
    echo "== Figure 14 (logical T + 36 H), error semantics $sem"
    echo "   36 programs: {naive, auto-corrected} x {d=23..31 uniform, d=24..30 hybrid} x {mean, 99.9th pct}"
    "$PYTHON" "$EXP_DIR/collect_results.py" --semantics "$sem" --data-root "$DATA_ROOT" --raw-dir "$OUT/$sem/raw" --output "$target"
  else
    echo "== Figure 14 (logical T + 36 H), error semantics $sem"
    echo "   row 1: 18 programs, {naive, auto-corrected} x {d=23..31 uniform, d=24..30 hybrid}, mean latency"
    echo "   row 2: decoding-latency sweep at d = 27, {naive, auto-corrected} x t_dec"
    tmp="$(mktemp -d "${TMPDIR:-/tmp}/figure14.XXXXXX")"
    "$PYTHON" "$EXP_DIR/collect_results.py" --semantics "$sem" --datasets mean --output "$tmp/row1.tex"
    "$PYTHON" "$EXP_DIR/collect_latency.py" --semantics "$sem" --output "$tmp/row2.tex"
    { cat "$tmp/row1.tex"; echo; cat "$tmp/row2.tex"; } > "$target"
    rm -rf "$tmp"
  fi
  "$SCRIPT_DIR/plot_figure13.sh" --semantics "$sem" --row2 "$ROW2" --results "$OUT" --tex-only
  echo
  cat "$target"
  echo
done
echo "Columns: err = error of q in %, time = SE cycles, space = physical qubits excluding the data block;"
echo "A = naive, B = auto-corrected. Results in $OUT"

# Render the figure with the paper's pgfplots code (skipped without LaTeX).
if command -v pdflatex >/dev/null; then
  "$SCRIPT_DIR/plot_figure13.sh" --semantics "$SEMANTICS" --row2 "$ROW2" --results "$OUT"
else
  echo "pdflatex not found: skipping the plot (scripts/plot_figure13.sh)"
fi
